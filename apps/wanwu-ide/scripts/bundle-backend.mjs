#!/usr/bin/env node
/**
 * Bundle the wanwu ACP backends into single self-contained ESM files that the
 * Electron app ships and runs with the bundled Electron binary as Node
 * (ELECTRON_RUN_AS_NODE). This removes any runtime dependency on pnpm/tsx or a
 * monorepo checkout (P0-1).
 */
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { mkdirSync } from "node:fs";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, "..");
const repoRoot = join(appDir, "..", "..");
const outDir = join(appDir, "resources");
mkdirSync(outDir, { recursive: true });

const targets = [
  {
    entry: join(repoRoot, "packages/wanwu-cli/src/index.ts"),
    outfile: join(outDir, "wanwu-cli.mjs"),
  },
  {
    entry: join(repoRoot, "packages/wanwu-cli/src/mockAcpServer.ts"),
    outfile: join(outDir, "wanwu-mock-acp.mjs"),
  },
];

for (const target of targets) {
  await build({
    entryPoints: [target.entry],
    outfile: target.outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    packages: "bundle",
    banner: { js: "// Wanwu-Code bundled ACP backend — generated by bundle-backend.mjs" },
    logLevel: "info",
  });
  console.log(`bundled ${target.outfile}`);
}
