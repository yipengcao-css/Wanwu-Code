If ((Test-Path $filelist) -eq $true)
{
    $caplist=(get-content $filelist)|Select-String "http"
    $filecount=$caplist.count
    $wipfolder=(split-path $filelist -Leaf).split(".")[0]
    $mergecapfilename=(split-path $filelist -Leaf).split(".")[0]

    if ($filecount -eq 0)
    {
        Write-UTCLog "Find Zero URL $filelist in $filelist, please check" -color "Red"
        exit
    }
    else
    {
        Write-UTCLog "Find $filecount URLs and download to $output\$wipfolder\" -color "Yellow" 
    }

    
    if ((Test-Path $output"\"$wipfolder"\") -eq $true)
    {
        Write-UTCLog "Download temp location (Exist): $output\$wipfolder, files exist will be skipped." -color "Yellow"
    }
    else
    {
        Write-UTCLog "Download temp location (NewCreated): $output\$wipfolder" -color "Green"
        mkdir $output"\"$wipfolder"\" | Out-Null
    }
    
    #get current time
    $st = Get-Date

    $i=1
    foreach ($url in $caplist)
    {
        #remove filename has %2F as host capture is using / (%2F) in filename
        $filename=($url.tostring().split("/")[4]).split("?")[0].Replace("%2F","_")  
        #Write-UTCLog "Filename to download $($filename)" -color "Green"
        $deviceloopip=($url.tostring()|Select-String -Pattern "\d{1,3}(\.\d{1,3}){3}" -AllMatches).Matches.Value  # search ip address in File name if this is everflow trace, prepare to merge the trace
        #Write-UTCLog "deviceloopip: $($deviceloopip)" -color "Green"
        if (-not [string]::IsNullOrEmpty($deviceloopip))
        {
            if ($deviceslist.count -eq 0)
            {
                $deviceslist+=$deviceloopip
            }
            else {
                if ( ($deviceslist|Where-Object {$_.toString() -eq $deviceloopip}).count -eq 0) 
                { $deviceslist+=$deviceloopip}
            }
        }
            
        if ((test-path $output"\"$wipfolder"\"$filename) )
        {
            Write-UTCLog "$i/$filecount : Skipping $output\$wipfolder\$filename" -color "Yellow"
        }
        else {
            #download logic -core 
            
            if (($thread -le 1) -or ((get-command "azcopy").count -eq 0) -or $useWebClient)  #if we do not have azcopy installed, or use webclient or thread count is 1, already use single thread
            { 
                #single threads
                if (((get-command "azcopy").count -eq 0) -or ($useWebClient)) #if we have azcopy installed or use $useWebClient switch is enabled, fall back to System.Net.WebClient download. otherwise use azcopy to speed up the download performance
                {
                    #this code path using $usewebclient should not be hit, but leave it as it. 
                    Write-UTCLog "$i/$filecount (s): (System.Net.WebClient) Downloading $filename" -color "Green"
                    $targetfile="$($output)\$($wipfolder)\$($filename)"
                    (New-Object System.Net.WebClient).DownloadFile($url, $targetfile)
                }
                else {
                    Write-UTCLog "$i/$filecount (s) : (azcopy10) Downloading $filename" -color "Green"                    
                    $cmd="azcopy copy ""$($url)"" $($output)\$($wipfolder)\$filename --check-md5 NoCheck"
                    Write-UTCLog "$cmd" "green"
                    Invoke-Expression $cmd
                }
            }
            else {

                #multi threads
                #check how many azcop already started, if the total count exceed thread count, wait until one of them finish
                $azcopycount=get-process|where-object {$_.name -eq "azcopy"}|measure-object|select-object -expandproperty count
                #wait loop to hold execution of azcopy if the total count exceed thread count
                while ($azcopycount -ge $thread)
                {
                    Write-UTCLog "azcopy count: $azcopycount, sleep 5 seconds" -color "gray"
                    Start-Sleep -Seconds 5
                    $azcopycount=get-process|where-object {$_.name -eq "azcopy"}|measure-object|select-object -expandproperty count
                }
                Write-UTCLog "$i/$filecount (m): (azcopy10) Downloading $filename" -color "Green"        
                # append "" to the url and filename to avoid special character issue in azcopy command line            
                $cmdarg="copy ""$($url)"" ""$($output)\$($wipfolder)\$filename"" --check-md5 NoCheck"
                if (Test-path "C:\ProgramData\chocolatey\lib\azcopy10\tools\azcopy\azcopy.exe") # if azcopy is installed by choco it might be duplicate process name for running azcopy as this is shimed 
                    {
                        $azcopycmd="C:\ProgramData\chocolatey\lib\azcopy10\tools\azcopy\azcopy.exe"
                    }
                    else{
                        $azcopycmd="azcopy"
                    }
                Write-UTCLog "$azcopycmd $cmdarg" "green"               
                Start-Process $azcopycmd -ArgumentList $cmdarg -WindowStyle Minimized
            }
            
        }
        $deviceloopip=$null
        $i++
    }

    #multithread clean up
    if ($thread -gt 1) #when multithread > 1, we need wait all azcopy job to be finished before processing merge or close. 
    {
        $azcopycount=get-process|where-object {$_.name -eq "azcopy"}|measure-object|select-object -expandproperty count
        #wait loop to hold execution of azcopy if the total count exceed thread count
        while ($azcopycount -gt 0)
        {
            Write-UTCLog "Wait for azcopy processes exit, sleep 1 second. (count: $azcopycount)" -color "gray"
            Start-Sleep -Seconds 1
            $azcopycount=get-process|where-object {$_.name -eq "azcopy"}|measure-object|select-object -expandproperty count
        }
    }
 
    $et=Get-Date
    # calculate time difference
    $diff=$et-$st
    # dsplay time difference in minutes
    Write-UTCLog "Download Files  Count: $($i),  Time(Mins) : $($diff.TotalMinutes), Time(Secs) $($diff.TotalSeconds)" -color "Cyan"   

    if ([string]::IsNullOrEmpty($deviceslist))
    {
        $downloadonly=$true   #overwrite the parameter if we cannot find any device ip address in filename, there is no point to merge host trace. 
    }
    else {
        Write-UTCLog "Total Devices: $deviceslist" -color "green"
    }
    
    if ($downloadonly)
    {
        Write-UTCLog "-DownloadOnly is TRUE or Downlod File does not seem to be EF files (cannot find device ip), pcap merge operations are skipped, -cleanup setting change to FALSE" -color "Yellow"
        $cleanup=$false
    }
    else {
        if ((Test-Path $mergecap) -eq $true)
        {
            Write-UTCLog "Merge trace file based on Device ipAddress, one file per device" -color "Green"
            #based on the device managed ip and merge trace per device
            foreach ($device in $deviceslist) {
                $filefilter= $output+"\"+$wipfolder+"\livesite*"+$device+".pcap"
                $capfilelist=get-childitem $filefilter
                $capfilecount=$capfilelist.count
                $i=1
                $devicename=Find-DeviceName -deviceip $device
                Write-UTCLog "Device $($deviceName) : $($device)" -color yellow
                foreach ($file in $capfilelist)
                {
                    $j=$i-1
                    if ((Test-path $output"\"$mergecapfilename"-"$device"_$j.pcapng"))
                    {
                        $para=" -w "+$output+"\"+$mergecapfilename+"-"+$device+"_$i.pcapng"+"  "+$file+" "+$output+"\"+$mergecapfilename+"-"+$device+"_$j.pcapng"
                        Start-Process -FilePath $mergecap $para -WorkingDirectory $output -Wait -WindowStyle Minimized
                        #copy-item $output"\"$mergecapfilename"-"$device".pcapng" $output"\"$mergecapfilename"-"$device"_temp.pcapng" -force
                        Remove-item $output"\"$mergecapfilename"-"$device"_$j.pcapng"  -force
                    }
                    else
                    {
                        copy-item $file $output"\"$mergecapfilename"-"$device"_$i.pcapng"  -force
                    }
                    Write-UTCLog "$i/$capfilecount Merging : $file" -color "Green"
                    $i++
                }
                #rename & append devicename (Find-DeviceName) to merged file
                rename-item $output"\"$mergecapfilename"-"$device"_"$capfilecount".pcapng" $output"\"$mergecapfilename"-"$device"-"$devicename"_"$capfilecount".pcapng"
                $string = "Output file : "+$mergecapfilename+"-"+$device+"-"+$devicename+"_"+$capfilecount+".pcapng"
                Write-UTCLog $string -color "Green"
            }

        }
        else {
            Write-UTCLog "Cannot merge cap due to $mergecap doese not exist, please reinstall wireshark"  -color "Yellow"
        }
    }

    if ($cleanup)
    {
        Write-UTCLog "Clean up $output\$wipfolder ..." -color "Yellow"
        Remove-Item $output"\"$wipfolder"\*.*" -Force
    }
    else {
        Write-UTCLog "-Cleanup is FALSE, Download temp location cleanup is skipped" -color "Yellow"
    }
  
}
else {
    Write-UTCLog "$filelist does not exsit, please check!" -color "RED"    
}
    
