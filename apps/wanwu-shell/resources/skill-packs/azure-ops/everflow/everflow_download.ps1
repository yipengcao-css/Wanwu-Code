Function SetAzcopy
{
    # search for azcopy.exe in temp folder if found, use Set-Alilas to config azcopy alias
    if (Test-path "$($env:temp)\azcopy\azcopy.exe")
    {
        Set-Alias -Name azcopy -Value "$($env:temp)\azcopy\azcopy.exe" -ErrorAction SilentlyContinue 
    }

    # Check if AzCopy is already installed
    if (-not (Get-Command azcopy -ErrorAction SilentlyContinue)) {

        Write-UTCLog "  azcopy wasn't found, download & unzip azcopy" -color "Yellow"
        # Download the AzCopy executable
        (New-Object System.Net.WebClient).DownloadFile("https://aka.ms/downloadazcopy-v10-windows", "$($env:temp)\azcopy.zip")
        
        #Fix bug 'reported by Ruben/Mohammad: Get-ChildItem may return an error when running in a normal user account.'
        # Extract the AzCopy executable
        Expand-Archive -Path "$($env:temp)\azcopy.zip" -DestinationPath "$($env:temp)\azcopy" -Force

        # Clean up the temporary files
        Remove-Item -Path "$($env:temp)\azcopy.zip" -Force

        #config azcopy alias and we can use in current session
        Set-Alias -Name azcopy -Value (Get-ChildItem "$($env:temp)\azcopy\azcopy.exe" -Recurse)[0].FullName

        # Verify that AzCopy is installed
        if (Get-Command azcopy -ErrorAction SilentlyContinue) {
            Write-UTCLog " $(azcopy --version) is installed."  "Green"
        } else {
            Write-UTCLog "azcopy installation failed."  "Red"
        }
    }
    else {
        Write-UTCLog "$(azcopy --version) is installed."  "Green"
    }

}

