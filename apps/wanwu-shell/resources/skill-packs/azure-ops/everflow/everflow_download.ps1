Function Write-UTCLog ([string]$message,[string]$color="green")
{
    	$logdate = ((get-date).ToUniversalTime()).ToString("yyyy-MM-dd HH:mm:ss")
    	$logstamp = "["+$logdate + "]," + $message
        Write-Host $logstamp -ForegroundColor $color
#    	Write-Output $logstamp | Out-File $logfile -Encoding ASCII -append
}

function Load-Kusto-Custom{

    $assembliesToLoad = @(
        "$($PSPath)\KustoCLI\Kusto.Data.dll",
        "$($PSPath)\KustoCLI\Microsoft.WindowsAzure.Security.Authentication.dll",
        "$($PSPath)\KustoCLI\Microsoft.WindowsAzure.Security.Authentication.Helpers.PassiveAuthHelper.dll",
        "$($PSPath)\KustoCLI\Microsoft.WindowsAzure.Security.Authentication.Logging.dll"
    )
    Write-UTCLog "Loading Customized Kusto..." -color "Green"
    $assembliesToLoad | ForEach-Object {
        $toLoad = $_
        try { 
			[Reflection.Assembly]::LoadFrom($toLoad) | Out-Null 
			#Write-UTCLog $toLoad  -color "Green"
        }
        catch {
            $type = $_.Exception.GetType()
            Write-Warning "Assembly $($toLoad) failed to load. Exception Type: $($type), Message: $($_.Exception.Message)"
        }
    }
}

function Invoke-Kusto {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $TRUE)][string]$kustoCluster,
        [Parameter(Mandatory = $False)][string]$kustoClusterSuffix,
        [Parameter(Mandatory = $TRUE)][string]$kustoDatabase,
        [Parameter(Mandatory = $TRUE)][string]$query,
        [Parameter(Mandatory = $False)]$Environment = "Public"
    )

    $attempt = 1
    do {
        Try {

            # Process the environment
            # if $KustoClusterSuffix is NULL, assign default kusto cluster suffix, if KustoClusterSuffix is not empty, use the parameter. 

            if ($kustoClusterSuffix -eq "")
            {
                switch ($Environment)
                {
                    "Mooncake"      {$kustoClusterSuffix = ".kusto.chinacloudapi.cn"}
                    "Fairfax"       {$kustoClusterSuffix = ".kusto.usgovcloudapi.net"}
                    "Blackforest"   {$kustoClusterSuffix = ".kusto.cloudapi.de"}
                    default         {$kustoClusterSuffix = ".kusto.windows.net"}
                }
            }
            switch ($Environment)
            {
                "Mooncake"      {$clusterConnectionString = "https://$kustoCluster$kustoClusterSuffix;AAD Federated Security=True";}
                "Fairfax"       {$clusterConnectionString = "https://$kustoCluster$kustoClusterSuffix;dSTS Federated Security=True";}
                "Blackforest"   {$clusterConnectionString = "https://$kustoCluster$kustoClusterSuffix;dSTS Federated Security=True";}
                default         {$clusterConnectionString = "https://$kustoCluster$kustoClusterSuffix;AAD Federated Security=True";}
            }

            if ($showkusto) {Write-UTCLog $clusterConnectionString -color "Yellow"}
            # Create a Kusto connection string.
            $connectionStringBuilder = New-Object Kusto.Data.KustoConnectionStringBuilder($clusterConnectionString, $kustoDatabase)
            $queryProvider = [Kusto.Data.Net.Client.KustoClientFactory]::CreateCslQueryProvider($connectionStringBuilder)
            $clientRequestProperties = New-Object Kusto.Data.Common.ClientRequestProperties

            # Set $clientRequestProperties, specifically a GUID for identification and a timeout threshold of one minute.
            $clientRequestProperties.ClientRequestId = 'MyPowerShellScript.ExecuteQuery.' + [guid]::NewGuid().Tostring()
            $clientRequestProperties.SetOption([Kusto.Data.Common.ClientRequestProperties]::OptionServerTimeout, [TimeSpan]::FromSeconds(45))

            # Execute the query and retrieve the resulting data table as a DataView.
            $reader = $queryProvider.ExecuteQuery($query, $clientRequestProperties)
            $dataTable = [Kusto.Cloud.Platform.Data.ExtendedDataReader]::ToDataSet($reader).Tables[0]

            # Create and return a $results object.
            $results = New-Object System.Data.DataView($dataTable)
            return $results
        }
        Catch {
            if ($_.Exception.Message.Contains("Caller is not authorized to perform this action"))
            {
                Write-UTCLog  "You do not have permission to access the Kusto cluster or database. Please check your permissions and here is the failed query" -color "Yellow"
                Write-UTCLog  "======Query: ==================" -color "Yellow"
                Write-UTCLog  $query 
                Write-UTCLog  "======Query: ==================" -color "Yellow"
            }
            if ($attempt -gt 3) 
                {
                    Write-UTCLog  'Kusto returned a critical error, such as a timeout or temporary throttle.' -color "Yellow"
                    Write-UTCLog  'Try again momentarily as this type of error is typically transient.'  -color "Yellow"
                    Write-UTCLog  "//********************************************** Query **********************************************//" -color "Yellow"
                    Write-UTCLog  $query
                    Write-UTCLog   "//********************************************** Exception ****************************************************//" -color "Yellow"
                    #throw $_
                    Write-UTCLog  $_.Exception.Message -color "Red"
                    return $null
                }
            sleep_bar -Time $(5 * $attempt) -message "Attempt $($attempt) : Query failed. Will retry in next $(5 * $attempt) seconds."
            }
            $attempt++
        } until ($success)
}


