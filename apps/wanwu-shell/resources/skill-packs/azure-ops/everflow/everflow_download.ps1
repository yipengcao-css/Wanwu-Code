$mergecap="C:\Program Files\Wireshark\mergecap.exe"
$capfilelist=""
$deviceslist=New-Object "System.Collections.Generic.List[string]"

#install azcopy if it does not exist
SetAzcopy

# determine thread count. 
if (($thread -le 1) -or ((get-command "azcopy").count -eq 0) -or $useWebClient) 
